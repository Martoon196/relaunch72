function taskFilterNav(active: CrmTaskFilter, tasks: readonly CrmTaskView[]): string {
  const openCount = tasks.filter((task) => task.status === 'open').length;
  const completeCount = tasks.filter((task) => task.status === 'completed').length;
  const filter = (id: CrmTaskFilter, href: string, label: string, itemCount: number): string =>
    `<a href="${href}"${active === id ? ' aria-current="page"' : ''}>${label} <span class="crm-visually-hidden">tasks: </span>${count(itemCount)}</a>`;
  return `<nav class="crm-filterlinks" aria-label="Task status filter">${filter('open', `${CRM_PORTAL_ROUTES.tasks}?status=open`, 'Open', openCount)}${filter('all', `${CRM_PORTAL_ROUTES.tasks}?status=all`, 'All', tasks.length)}${filter('completed', `${CRM_PORTAL_ROUTES.tasks}?status=completed`, 'Completed', completeCount)}</nav>`;
}

function taskCompleteForm(task: CrmTaskView, csrfToken: string, canWrite: boolean): string {
  if (!canWrite) return '<p class="crm-card-note" role="status">Read-only access · task changes are unavailable for your workspace role.</p>';
  if (!validCsrfToken(csrfToken) || !validVersion(task.rowVersion) || !validCommandKey(task.completeCommandKey)) {
    return '<p class="crm-card-note" role="status">Refresh this page before completing this task.</p>';
  }
  return `<form class="crm-complete-form" method="post" action="${CRM_PORTAL_ROUTES.tasks}/${encodeURIComponent(task.id)}/complete" aria-label="Mark ${escapeHtml(task.title)} complete">${hiddenMutationFields(csrfToken, task.completeCommandKey, task.rowVersion)}<button class="button secondary compact" type="submit">Mark complete</button><p>Updates this CRM task only · no message is sent.</p></form>`;
}

function taskList(snapshot: CrmWorkspaceSnapshot, filter: CrmTaskFilter, csrfToken: string): string {
  const tasks = filter === 'all' ? snapshot.tasks : snapshot.tasks.filter((task) => task.status === filter);
  if (tasks.length === 0) {
    const message = filter === 'open'
      ? 'There are no open tasks in this workspace.'
      : filter === 'completed'
        ? 'No tasks have been marked complete yet.'
        : 'Tasks created with leads will appear here.';
    return emptyState('calendar', `No ${filter === 'all' ? '' : `${filter} `}tasks`, message);
  }
  return `<ol class="crm-task-list">${tasks.map((task, index) => {
    const context = [task.contactName, task.opportunityTitle].filter((value): value is string => typeof value === 'string' && value.trim() !== '');
    const due = task.status === 'completed' ? task.completedAt : task.dueAt;
    const overdue = task.status === 'open' && isOverdue(task.dueAt, snapshot.workspace.snapshotAt);
    const statusLabel = task.status === 'completed' ? 'Completed' : task.status === 'cancelled' ? 'Cancelled' : 'Open';
    return `<li class="crm-task"><div><h3 id="crm-task-${index}-title">${escapeHtml(task.title)}</h3><p class="crm-task-context">${context.length ? context.map(escapeHtml).join(' · ') : 'Workspace task'}${task.assigneeName ? ` · ${escapeHtml(task.assigneeName)}` : ''}</p><div class="crm-task-meta"><span class="crm-task-status${task.status === 'completed' ? ' completed' : ''}">${statusLabel}</span>${due ? `<span class="crm-due-state${overdue ? ' overdue' : ''}">${overdue ? 'Overdue · ' : task.status === 'completed' ? 'Completed · ' : 'Due · '}${dateTime(due, snapshot.workspace.timezone, 'Time unavailable')}</span>` : ''}</div></div>${task.status === 'open' ? taskCompleteForm(task, csrfToken, snapshot.workspace.canWrite) : ''}</li>`;
  }).join('')}</ol>`;
}

