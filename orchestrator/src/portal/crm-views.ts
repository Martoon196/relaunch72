function opportunityMoveForm(opportunity: CrmOpportunityView, stages: readonly CrmStageView[], csrfToken: string, formIndex: number, canWrite: boolean): string {
  if (!canWrite) return '<p class="crm-card-note" role="status">Read-only access · stage changes are unavailable for your workspace role.</p>';
  const alternatives = stages.filter((stage) => stage.id !== opportunity.stageId);
  if (alternatives.length === 0) return '<p class="crm-card-note">No other saved stage is available.</p>';
  if (!validCsrfToken(csrfToken) || !validVersion(opportunity.rowVersion) || !validCommandKey(opportunity.moveCommandKey)) {
    return '<p class="crm-card-note" role="status">Refresh this page before moving this opportunity.</p>';
  }
  const selectId = `crm-move-stage-${formIndex}`;
  return `<form class="crm-move-form" method="post" action="${CRM_PORTAL_ROUTES.pipeline}/${encodeURIComponent(opportunity.id)}/stage" aria-label="Move ${escapeHtml(opportunity.title)} to another stage">
    ${hiddenMutationFields(csrfToken, opportunity.moveCommandKey, opportunity.rowVersion)}
    <div class="crm-move-field"><label for="${selectId}">Move to</label><select id="${selectId}" name="target_stage_id" required>${alternatives.map((stage) => `<option value="${escapeHtml(stage.id)}">${escapeHtml(stage.name)}</option>`).join('')}</select></div>
    <button class="button secondary" type="submit">Move stage</button>
  </form><p class="crm-card-note">Saves the CRM stage and activity only · no contact is notified.</p>`;
}

function pipelineBoard(snapshot: CrmWorkspaceSnapshot, csrfToken: string): string {
  const stages = [...snapshot.stages].sort((left, right) => left.position - right.position);
  if (stages.length === 0) {
    return emptyState('pipeline', 'No pipeline stages have been saved', 'Create the workspace pipeline before adding or moving opportunities.', 'crm-board-empty');
  }
  let cardIndex = 0;
  const columns = stages.map((stage, stageIndex) => {
    const opportunities = snapshot.opportunities.filter((opportunity) => opportunity.stageId === stage.id);
    const cards = opportunities.length === 0
      ? '<p class="crm-stage-empty">No opportunities in this stage.</p>'
      : opportunities.map((opportunity) => {
        const index = cardIndex++;
        return opportunityCardWithToken(opportunity, stages, snapshot, csrfToken, index);
      }).join('');
    return `<section class="crm-stage-column crm-stage-tone-${stageIndex % 6}" aria-labelledby="crm-stage-${stageIndex}-title"><div class="crm-stage-head"><h2 id="crm-stage-${stageIndex}-title">${escapeHtml(stage.name)}</h2><span class="crm-stage-total">${count(opportunities.length)}</span></div><div class="crm-stage-cards">${cards}</div></section>`;
  });
  const orphaned = snapshot.opportunities.filter((opportunity) => !stages.some((stage) => stage.id === opportunity.stageId));
  if (orphaned.length > 0) {
    const cards = orphaned.map((opportunity) => opportunityCardWithToken(opportunity, stages, snapshot, csrfToken, cardIndex++)).join('');
    columns.push(`<section class="crm-stage-column crm-stage-tone-4" aria-labelledby="crm-stage-needs-review"><div class="crm-stage-head"><h2 id="crm-stage-needs-review">Stage needs review</h2><span class="crm-stage-total">${count(orphaned.length)}</span></div><p class="crm-card-note">These records reference a stage that is no longer available. Move each one to a saved stage.</p><div class="crm-stage-cards">${cards}</div></section>`);
  }
  return `<div class="crm-board" aria-label="Opportunity stages">${columns.join('')}</div>`;
}

function opportunityCardWithToken(opportunity: CrmOpportunityView, stages: readonly CrmStageView[], snapshot: CrmWorkspaceSnapshot, csrfToken: string, index: number): string {
  const nextTask = opportunity.nextTaskAt
    ? `${isOverdue(opportunity.nextTaskAt, snapshot.workspace.snapshotAt) ? '<span class="crm-visually-hidden">Overdue: </span>' : ''}${dateTime(opportunity.nextTaskAt, snapshot.workspace.timezone)}`
    : 'No next task';
  return `<article class="crm-opportunity" aria-labelledby="crm-opportunity-${index}-title"><h3 id="crm-opportunity-${index}-title">${escapeHtml(opportunity.title)}</h3><p class="crm-opportunity-contact">${escapeHtml(opportunity.contactName)}${opportunity.companyName ? ` · ${escapeHtml(opportunity.companyName)}` : ''}</p><div class="crm-opportunity-meta">
    <div class="crm-meta-item"><span>Value</span><strong>${escapeHtml(formatMoney(opportunity.valueMinor, opportunity.currency))}</strong></div>
    <div class="crm-meta-item"><span>Owner</span><strong>${escapeHtml(opportunity.ownerName?.trim() || 'Unassigned')}</strong></div>
    <div class="crm-meta-item"><span>Expected close</span><strong>${calendarDate(opportunity.expectedCloseDate)}</strong></div>
    <div class="crm-meta-item"><span>Next task</span><strong>${nextTask}</strong></div>
  </div>${opportunityMoveForm(opportunity, stages, csrfToken, index, snapshot.workspace.canWrite)}</article>`;
}

