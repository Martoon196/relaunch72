/**
 * Pure server-rendered CRM body fragments for the first durable portal loop.
 *
 * Integration contract:
 * - Insert one renderer's output into `appShell` as its `body`.
 * - The controller supplies a request-bound CSRF token and stable command keys.
 * - The POST handlers must re-check workspace scope, permission, input, command
 *   idempotency and `expected_version`; these views are presentation only.
 * - Every customer-controlled value is escaped here. Route paths are fixed and
 *   object identifiers are URL encoded before entering a form action.
 *
 * Each body includes the small CRM extension stylesheet so it can be integrated
 * without editing the shared design system first. It can be moved into the page
 * head later without changing the renderer contract.
 */

