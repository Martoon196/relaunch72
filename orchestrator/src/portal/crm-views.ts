function pageHeading(workspace: CrmWorkspaceView, active: 'contacts' | 'pipeline' | 'tasks', title: string, summary: string): string {
  const snapshot = formatDateTime(workspace.snapshotAt, workspace.timezone);
  return `<header class="page-heading crm-page-heading"><div><div class="eyebrow">${icon(active === 'contacts' ? 'contacts' : active === 'pipeline' ? 'pipeline' : 'calendar')}CRM · saved workspace records</div><h1>${escapeHtml(title)}</h1><p>${escapeHtml(summary)}</p><div class="crm-heading-meta"><span>${escapeHtml(workspace.name)}</span>${snapshot ? `<span aria-hidden="true">·</span><span>Viewed ${escapeHtml(snapshot.label)}</span>` : ''}</div></div></header>`;
}

function notice(view: CrmNotice | undefined): string {
  if (!view) return '';
  const role = view.kind === 'error' || view.kind === 'conflict' ? 'alert' : 'status';
  const symbol = view.kind === 'success' ? 'activity' : view.kind === 'info' ? 'activity' : 'lock';
  return `<div class="crm-notice ${view.kind}" role="${role}">${icon(symbol)}<div><strong>${escapeHtml(view.title)}</strong><p>${escapeHtml(view.message)}</p></div></div>`;
}

function emptyState(iconName: 'contacts' | 'pipeline' | 'calendar' | 'activity', title: string, message: string, extraClass = ''): string {
  return `<div class="crm-empty${extraClass ? ` ${extraClass}` : ''}" role="status">${icon(iconName)}<strong>${escapeHtml(title)}</strong><p>${escapeHtml(message)}</p></div>`;
}

function primaryReach(contact: CrmContactView): string {
  const email = contact.primaryEmail?.trim();
  const phone = contact.primaryPhone?.trim();
  if (email && phone) return `${escapeHtml(email)}<span class="crm-secondary">${escapeHtml(phone)}</span>`;
  return escapeHtml(email || phone || 'Not supplied');
}

function contactsTable(snapshot: CrmWorkspaceSnapshot): string {
  if (snapshot.contacts.length === 0) {
    return emptyState('contacts', 'No leads in this workspace yet', 'Use the create lead form to add the first private CRM record. No message will be sent.');
  }
  const rows = snapshot.contacts.map((contact) => `<tr>
    <td data-label="Contact"><span class="crm-contact-name">${escapeHtml(contact.displayName)}</span>${contact.companyName ? `<span class="crm-contact-company">${escapeHtml(contact.companyName)}</span>` : ''}</td>
    <td data-label="Primary reach"><span class="crm-reach">${primaryReach(contact)}</span></td>
    <td data-label="Lifecycle"><span class="crm-lifecycle">${escapeHtml(contact.lifecycle)}</span></td>
    <td data-label="Open deals"><span class="crm-number">${count(contact.openOpportunityCount)}</span></td>
    <td class="crm-optional-column" data-label="Next task"><span class="crm-date">${dateTime(contact.nextTaskAt, snapshot.workspace.timezone, 'None')}</span></td>
    <td class="crm-optional-column" data-label="Last activity"><span class="crm-date">${dateTime(contact.lastActivityAt, snapshot.workspace.timezone, 'No activity')}</span></td>
  </tr>`).join('');
  return `<div class="crm-table-wrap"><table class="crm-table"><caption>Contacts saved in ${escapeHtml(snapshot.workspace.name)}</caption><thead><tr><th scope="col">Contact</th><th scope="col">Primary reach</th><th scope="col">Lifecycle</th><th scope="col">Open deals</th><th class="crm-optional-column" scope="col">Next task</th><th class="crm-optional-column" scope="col">Last activity</th></tr></thead><tbody>${rows}</tbody></table></div>`;
}

function fieldErrors(state: CreateLeadFormState | undefined, field: CreateLeadField): readonly string[] {
  const errors = state?.fieldErrors?.[field];
  return Array.isArray(errors) ? errors.filter((error): error is string => typeof error === 'string' && error.trim() !== '') : [];
}

function errorAttributes(state: CreateLeadFormState | undefined, field: CreateLeadField): string {
  const errors = fieldErrors(state, field);
  return errors.length > 0
    ? ` aria-invalid="true" aria-describedby="${LEAD_FIELD_IDS[field]}-error"`
    : '';
}

function inlineErrors(state: CreateLeadFormState | undefined, field: CreateLeadField): string {
  const errors = fieldErrors(state, field);
  return errors.length > 0
    ? `<p class="crm-field-error" id="${LEAD_FIELD_IDS[field]}-error">${errors.map(escapeHtml).join(' ')}</p>`
    : '';
}

function leadErrorSummary(state: CreateLeadFormState | undefined): string {
  const entries = (Object.keys(LEAD_FIELD_IDS) as CreateLeadField[]).flatMap((field) =>
    fieldErrors(state, field).map((error) => ({ field, error })));
  if (entries.length === 0) return '';
  return `<div class="crm-error-summary" role="alert" tabindex="-1"><strong>Check the lead details</strong><ul>${entries.map(({ field, error }) => `<li><a href="#${LEAD_FIELD_IDS[field]}">${escapeHtml(LEAD_FIELD_LABELS[field])}: ${escapeHtml(error)}</a></li>`).join('')}</ul></div>`;
}

function createLeadForm(snapshot: CrmWorkspaceSnapshot, options: ContactsPageOptions): string {
  const stages = snapshot.stages.filter((stage) => !stage.isClosed)
    .sort((left, right) => left.position - right.position);
  if (!snapshot.workspace.canWrite) {
    return `<div class="crm-unavailable" role="status"><strong>Read-only CRM access.</strong><br>Your workspace role can review contacts, opportunities and tasks but cannot create or change records.</div>`;
  }
  if (stages.length === 0) {
    return `<div class="crm-unavailable" role="status"><strong>Lead creation is not available yet.</strong><br>The workspace needs at least one open pipeline stage before an opportunity can be created.</div>`;
  }
  if (!validCsrfToken(options.csrfToken) || !validCommandKey(options.createLeadCommandKey)) {
    return `<div class="crm-unavailable" role="status"><strong>Refresh needed.</strong><br>A secure form token is missing or a new command key is required before this form can safely save a lead.</div>`;
  }
  const values = options.form?.values ?? {};
  const selectedStage = stages.some((stage) => stage.id === values.stageId) ? values.stageId : stages[0]!.id;
  return `<form class="crm-form" method="post" action="${CRM_PORTAL_ROUTES.createLead}">
    ${hiddenMutationFields(options.csrfToken, options.createLeadCommandKey)}
    ${leadErrorSummary(options.form)}
    <fieldset class="crm-fieldset"><legend class="crm-legend">Contact</legend><div class="crm-field-grid">
      <div class="crm-field full"><label for="${LEAD_FIELD_IDS.display_name}">Contact name</label><input id="${LEAD_FIELD_IDS.display_name}" name="display_name" type="text" autocomplete="name" maxlength="160" value="${escapeHtml(values.displayName)}" required${errorAttributes(options.form, 'display_name')}>${inlineErrors(options.form, 'display_name')}</div>
      <div class="crm-field full"><label for="${LEAD_FIELD_IDS.company_name}">Company <span>optional</span></label><input id="${LEAD_FIELD_IDS.company_name}" name="company_name" type="text" autocomplete="organization" maxlength="160" value="${escapeHtml(values.companyName)}"${errorAttributes(options.form, 'company_name')}>${inlineErrors(options.form, 'company_name')}</div>
      <div class="crm-field"><label for="${LEAD_FIELD_IDS.email}">Email address <span>optional</span></label><input id="${LEAD_FIELD_IDS.email}" name="email" type="email" inputmode="email" autocomplete="email" autocapitalize="none" spellcheck="false" maxlength="254" value="${escapeHtml(values.email)}"${errorAttributes(options.form, 'email')}>${inlineErrors(options.form, 'email')}</div>
      <div class="crm-field"><label for="${LEAD_FIELD_IDS.phone}">Phone number <span>optional</span></label><input id="${LEAD_FIELD_IDS.phone}" name="phone" type="tel" inputmode="tel" autocomplete="tel" maxlength="40" value="${escapeHtml(values.phone)}"${errorAttributes(options.form, 'phone')}>${inlineErrors(options.form, 'phone')}</div>
      <p class="crm-field-hint full">Add an email address, phone number, or both. Saving the record does not contact the person.</p>
    </div></fieldset>
    <fieldset class="crm-fieldset"><legend class="crm-legend">Opportunity</legend><div class="crm-field-grid">
      <div class="crm-field full"><label for="${LEAD_FIELD_IDS.opportunity_title}">Opportunity name</label><input id="${LEAD_FIELD_IDS.opportunity_title}" name="opportunity_title" type="text" maxlength="180" value="${escapeHtml(values.opportunityTitle)}" required${errorAttributes(options.form, 'opportunity_title')}>${inlineErrors(options.form, 'opportunity_title')}</div>
      <div class="crm-field full"><label for="${LEAD_FIELD_IDS.stage_id}">Starting stage</label><select id="${LEAD_FIELD_IDS.stage_id}" name="stage_id" required${errorAttributes(options.form, 'stage_id')}>${stages.map((stage) => `<option value="${escapeHtml(stage.id)}"${stage.id === selectedStage ? ' selected' : ''}>${escapeHtml(stage.name)}</option>`).join('')}</select>${inlineErrors(options.form, 'stage_id')}</div>
    </div></fieldset>
    <fieldset class="crm-fieldset"><legend class="crm-legend">First task <span class="crm-secondary">optional</span></legend><div class="crm-field-grid">
      <div class="crm-field full"><label for="${LEAD_FIELD_IDS.task_title}">Task</label><input id="${LEAD_FIELD_IDS.task_title}" name="task_title" type="text" maxlength="180" value="${escapeHtml(values.taskTitle)}"${errorAttributes(options.form, 'task_title')}>${inlineErrors(options.form, 'task_title')}</div>
      <div class="crm-field full"><label for="${LEAD_FIELD_IDS.task_due_at}">Due date and time <span>workspace time</span></label><input id="${LEAD_FIELD_IDS.task_due_at}" name="task_due_at" type="datetime-local" value="${escapeHtml(values.taskDueAt)}"${errorAttributes(options.form, 'task_due_at')}>${inlineErrors(options.form, 'task_due_at')}</div>
    </div></fieldset>
    <div class="crm-form-foot"><button class="button" type="submit">${icon('contacts')}Create lead in CRM</button><div class="crm-effect-note">${icon('lock')}<span>Creates private contact, opportunity and optional task records only. It does not send a message, schedule content or notify the contact.</span></div></div>
  </form>`;
}

function timelinePanel(snapshot: CrmWorkspaceSnapshot): string {
  const items = snapshot.timeline.slice(0, 12);
  const body = items.length === 0
    ? emptyState('activity', 'No CRM activity recorded yet', 'Saved lead, stage and task actions will appear here. This is not a message-delivery log.')
    : `<ol class="crm-timeline">${items.map((item) => {
      const marker = item.kind === 'lead_created' ? '+' : item.kind === 'stage_moved' ? '→' : item.kind === 'task_completed' ? '✓' : '•';
      const actor = item.actorName?.trim() ? ` · ${escapeHtml(item.actorName)}` : '';
      return `<li class="crm-timeline-item"><span class="crm-timeline-mark" aria-hidden="true">${marker}</span><div class="crm-timeline-copy"><p>${escapeHtml(item.summary)}</p><small>${dateTime(item.occurredAt, snapshot.workspace.timezone, 'Time unavailable')}${actor}</small></div></li>`;
    }).join('')}</ol>`;
  return `<section class="crm-panel" aria-labelledby="crm-timeline-title"><div class="crm-panel-head"><div><h2 id="crm-timeline-title">Recent CRM activity</h2><p>Recorded workspace changes · newest first</p></div>${icon('activity')}</div><div class="crm-panel-body">${body}</div></section>`;
}

