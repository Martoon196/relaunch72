function count(value: unknown): string {
  return Number.isSafeInteger(value) && Number(value) >= 0
    ? new Intl.NumberFormat('en-GB').format(Number(value))
    : '—';
}

function safeDate(value: unknown): Date | null {
  if (typeof value !== 'string' || value.trim() === '') return null;
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? null : date;
}

function formatDateTime(value: unknown, timezone: string): { datetime: string; label: string } | null {
  const date = safeDate(value);
  if (!date) return null;
  const datetime = date.toISOString();
  const options: Intl.DateTimeFormatOptions = {
    dateStyle: 'medium', timeStyle: 'short', timeZone: timezone,
  };
  try {
    return { datetime, label: new Intl.DateTimeFormat('en-GB', options).format(date) };
  } catch {
    return {
      datetime,
      label: `${new Intl.DateTimeFormat('en-GB', { ...options, timeZone: 'UTC' }).format(date)} UTC`,
    };
  }
}

function dateTime(value: unknown, timezone: string, fallback = 'Not set'): string {
  const formatted = formatDateTime(value, timezone);
  return formatted
    ? `<time datetime="${escapeHtml(formatted.datetime)}">${escapeHtml(formatted.label)}</time>`
    : escapeHtml(fallback);
}

function calendarDate(value: unknown, fallback = 'Not set'): string {
  if (typeof value !== 'string') return escapeHtml(fallback);
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  if (!match) return escapeHtml(fallback);
  const date = new Date(Date.UTC(Number(match[1]), Number(match[2]) - 1, Number(match[3])));
  if (date.getUTCFullYear() !== Number(match[1]) || date.getUTCMonth() !== Number(match[2]) - 1
      || date.getUTCDate() !== Number(match[3])) return escapeHtml(fallback);
  const label = new Intl.DateTimeFormat('en-GB', { dateStyle: 'medium', timeZone: 'UTC' }).format(date);
  return `<time datetime="${escapeHtml(value)}">${escapeHtml(label)}</time>`;
}

function isOverdue(dueAt: unknown, snapshotAt: unknown): boolean {
  const due = safeDate(dueAt);
  const snapshot = safeDate(snapshotAt);
  return !!due && !!snapshot && due.getTime() < snapshot.getTime();
}

function formatMoney(valueMinor: unknown, currency: unknown): string {
  if (typeof valueMinor !== 'number' || !Number.isSafeInteger(valueMinor)) return 'Value not set';
  if (typeof currency !== 'string' || !/^[A-Z]{3}$/.test(currency)) return 'Value unavailable';
  try {
    return new Intl.NumberFormat('en-GB', { style: 'currency', currency }).format(valueMinor / 100);
  } catch {
    return 'Value unavailable';
  }
}

function validVersion(value: unknown): value is number {
  return typeof value === 'number' && Number.isSafeInteger(value) && value >= 1;
}

function validCommandKey(value: unknown): value is string {
  return typeof value === 'string' && /^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$/.test(value);
}

function validCsrfToken(value: unknown): value is string {
  return typeof value === 'string' && value.length > 0 && value.length <= 4096;
}

function hiddenMutationFields(csrfToken: string, commandKey: string, expectedVersion?: number): string {
  const version = expectedVersion === undefined
    ? ''
    : `<input type="hidden" name="expected_version" value="${escapeHtml(expectedVersion)}">`;
  return `<input type="hidden" name="_csrf" value="${escapeHtml(csrfToken)}"><input type="hidden" name="command_key" value="${escapeHtml(commandKey)}">${version}`;
}

